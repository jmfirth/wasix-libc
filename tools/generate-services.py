import sys

class Ports:
    def __init__(self, port: tuple[str, str]):
        self.entries = []
        self.add(port)

    def add(self, port: tuple[str, str]):
        self.entries.append(port)

class Services:
    _instance = None

    ports = dict()

    def __new__(cls, _):
        if cls._instance is None:
            cls._instance = super(Services, cls).__new__(cls)
        return cls._instance

    def __init__(self, filename):
        self.__load(filename)

    def __load(self, filename):
        for line in open(filename):
            if line[0:1] == '#' or line.isspace():
                continue
            line = line[:-1] # drop newline
            self.add(line)

    def add(self, line: str):
        (name, rest) = line.split(None)
        (port, proto) = rest.split('/')
        if name in self.ports:
            self.ports[name].add((port, proto))
        else:
            self.ports[name] = Ports((port, proto))

    def num_ports(self):
        return len(self.ports)


    def generate(self, filename, max_entries=1000):
        entries = list(self.ports.items())[:max_entries]
        with open(filename, 'w') as f:
            f.write('#include <uthash.h>\n#include "lock.h"\n#include "libc.h"\n\n')
            f.write('#include "lookup.h"\n#include "services.h"\n\n')
            f.write('/* Generated by tools/generate-services.py. */\n')
            f.write('services_entry_t *services = NULL;\n')
            f.write(f'static services_entry_t static_services_entries[{len(entries)}];\n')
            f.write('/* Set, under the lock, only once the whole table is built. */\n')
            f.write('static int services_ready;\n')
            f.write('#ifdef _REENTRANT\nstatic volatile int services_lock[1];\n#endif\n\n')
            f.write('/* The lock is not on fork.c\'s lock list (a named lock pointer or an atfork\n')
            f.write(' * handler would be a new provider generation: the shared libc exports every\n')
            f.write(' * symbol and imports a table sized by the function addresses it takes). So a\n')
            f.write(' * fork child can inherit the lock held by a thread it does not have, and a\n')
            f.write(' * table that thread was half-way through building. A process with one thread\n')
            f.write(' * cannot have the lock legitimately held on entry, so it is cleared first; and\n')
            f.write(' * a table that is not marked ready is rebuilt from nothing. */\n')
            f.write('static void services_lock_acquire(void) {\n#ifdef _REENTRANT\n')
            f.write('  if (!libc.threads_minus_1) services_lock[0] = 0;\n#endif\n')
            f.write('  LOCK(services_lock);\n}\n\n')
            f.write('services_entry_t *get_entry(const char *name) {\n')
            f.write('  services_entry_t *out;\n  HASH_FIND_STR(services, name, out);\n  return out;\n}\n\n')
            f.write('void add_entry(int idx, char *name, int svcs_len, const struct service *svc) {\n')
            f.write('  static_services_entries[idx].name = name;\n')
            f.write('  static_services_entries[idx].svcs = svc;\n')
            f.write('  static_services_entries[idx].len_svcs = svcs_len;\n')
            f.write('  HASH_ADD_STR(services, name, &static_services_entries[idx]);\n}\n\n')
            # Every lookup calls init_services before walking the immutable hash.
            # Lock even the initialized check, so no reader sees a partial build.
            f.write('void init_services(void) {\n\tservices_lock_acquire();\n')
            f.write('\tif (services_ready) {\n\t\tUNLOCK(services_lock);\n\t\treturn;\n\t}\n')
            f.write('\tservices = NULL;\n')
            for i, (name, ports) in enumerate(entries):
                supported = [(port, proto) for port, proto in ports.entries
                             if proto in ('tcp', 'udp')]
                f.write(f'\tstatic const struct service svc_{i}[] = {{\n')
                for port, proto in supported:
                    socktype = 'SOCK_STREAM' if proto == 'tcp' else 'SOCK_DGRAM'
                    f.write(f'\t\t{{{port}, IPPROTO_{proto.upper()}, {socktype}}},\n')
                f.write('\t};\n')
                f.write(f'\tadd_entry({i}, "{name}", {len(supported)}, svc_{i});\n')
            f.write('\tservices_ready = 1;\n\tUNLOCK(services_lock);\n}\n')


if __name__ == "__main__":
    max_entries = 1000
    if len(sys.argv) > 1:
        max_entries = sys.argv[1]
    print(max_entries)
    ss = Services("/etc/services")
    ss.generate("services.c", int(max_entries))

